"""
Claim 2 (application A, REAL-DATA version) - GESPI conformal RISK CONTROL on REAL AlphaFold DB
predictions vs REAL experimental structures (Section 4.1's task, real protein instances).

This replaces the illustrative sigmoid-DGP of repro_claim2a.py with MEASURED (confidence, error)
pairs for real proteins: AlphaFold2 is NOT run here (out of CPU scope, per the paper); instead we
download AlphaFold DB's already-computed, public predicted structures (real pLDDT confidence,
DeepMind/EMBL-EBI, https://alphafold.ebi.ac.uk) for a curated panel of real UniProt proteins, and
the REAL experimental structures for the SAME proteins from the RCSB PDB (https://www.rcsb.org),
then compute a REAL per-residue error indicator: after a Kabsch (least-squares) superposition of
the predicted structure onto the real experimental structure (residues matched by pairwise sequence
alignment, so no reliance on matching residue numbering), e = 1 if the post-superposition CA-CA
distance > 3 Angstrom, else 0. This is exactly the error criterion used in the paper text and in
repro_claim2a.py's DGP ("err > 3 Angstrom"), now measured on real coordinates instead of simulated.

GESPI itself (Eq. 2, the min/max threshold construction) and conformal risk control (Angelopoulos
et al. 2024) are UNCHANGED from repro_claim2a.py - only the data source changes: real measured
(c, e) residue pairs instead of a sigmoid law.

Data sources (all public, no login, no GPU, downloaded fresh unless already cached locally under
real_data_cache/):
  - AlphaFold DB REST API + files: https://alphafold.ebi.ac.uk/api/prediction/{UniProt}
                                     -> pdbUrl (predicted structure with pLDDT in the B-factor column)
  - RCSB PDB:                       https://files.rcsb.org/download/{PDBID}.pdb  (real, experimental)

Curated real-protein panel (19 successfully processed; see PANEL below for exact UniProt/PDB/chain
IDs and provenance). 16 are well-characterized single-domain proteins that AlphaFold predicts with
near-zero real error (the "EASY" pool). 3 are real, substantially harder cases where AlphaFold's
predicted structure disagrees with the real experimental structure much more often despite still
being moderately-to-highly confident: the SARS-CoV-2 spike glycoprotein monomer prediction vs the
real cryo-EM trimer structure (6VXX), an isolated fibronectin FN-III module (1FNF) vs the
full-length multi-domain AF model, and the Ca2+-binding light chain of coagulation Factor X (1XKA)
vs its calcium-free AF model (the "HARD" pool).

The REAL analogue of repro_claim2a.py's "over-optimistic adversarial synthetic" regime is built from
these two real pools directly, with NO invented shift: a synthetic-augmentation set drawn only from
the EASY pool (well-characterized proteins that happen to be uniformly easy) looks safe in isolation,
but the TRUE real-world deployment distribution (the fixed test pool, bootstrapped from the full
mixed easy+hard panel) also contains real proteins like the ones in the HARD pool, where confidence
does not reliably track accuracy. Calibrating "OnlySynth"/"NaivePooled" only on the easy-only
synthetic sample and then deploying on the real mixed distribution is the honest, real-data analogue
of the paper's synthetic-data-quality hazard - obtained by choosing which REAL proteins go in the
synthetic-augmentation set, not by shifting a simulated law.

Because the curated real panel has only 19 proteins (4134 measured residues total) - far fewer
than the paper's N=1000 synthetic proteins - Monte-Carlo trials are generated by NONPARAMETRIC
BOOTSTRAP: resampling residues WITH REPLACEMENT from the fixed, real, measured (c, e) pool. Since
resampling with replacement from a finite population is exactly equivalent in distribution to i.i.d.
draws from that population's empirical law, this preserves the "T trials with an MC standard error"
structure of repro_claim2a.py while every draw is built exclusively from real measured values (no
invented probability law). All reported precision is therefore bounded by the real panel's finite
size - stated explicitly in the output.

Paper knobs matched: real proteins n=10 (used to size the real-calibration draw, Rr = n*M, M=50, as
in repro_claim2a.py), alpha in {5,10,15}%, eps=5%. "N=1000 synthetic proteins" is approximated by a
Rs=5000-residue bootstrap draw (matching repro_claim2a.py's Rs), since we do not have 1000 distinct
real synthetic proteins; this is a real limitation, stated explicitly below and in the logbook page.
"""
