def fetch(url, dest):
    if dest.exists():
        return dest.read_bytes()
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    data = urllib.request.urlopen(req, timeout=60).read()
    dest.write_bytes(data)
    return data

def af_pdb_url(uniprot):
    url = f"https://alphafold.ebi.ac.uk/api/prediction/{uniprot}"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    data = json.load(urllib.request.urlopen(req, timeout=30))
    return data[0]["pdbUrl"]

def extract_chain(pdb_bytes, chain_id):
    from Bio.PDB import PDBParser
    parser = PDBParser(QUIET=True)
    struct = parser.get_structure("s", io.StringIO(pdb_bytes.decode("utf-8", errors="ignore")))
    model = next(iter(struct))
    chain = model[chain_id]
    seq, coords, bfac = [], [], []
    for res in chain:
        resname = res.get_resname()
        if resname not in AA3TO1 or "CA" not in res:
            continue
        seq.append(AA3TO1[resname])
        coords.append(res["CA"].get_coord())
        bfac.append(res["CA"].get_bfactor())
    return "".join(seq), np.array(coords, dtype=np.float64), np.array(bfac, dtype=np.float64)

def kabsch_error(mobile, fixed):
    mc = mobile - mobile.mean(axis=0); fc = fixed - fixed.mean(axis=0)
    U, S, Vt = np.linalg.svd(mc.T @ fc)
    d = np.sign(np.linalg.det(Vt.T @ U.T))
    R = Vt.T @ np.diag([1, 1, d]) @ U.T
    fit = (R @ mc.T).T + fixed.mean(axis=0)
    return np.linalg.norm(fit - fixed, axis=1)

def align_and_measure(uniprot, pdb_id, chain_id):
    from Bio.Align import PairwiseAligner, substitution_matrices
    af_url = af_pdb_url(uniprot)
    af_bytes = fetch(af_url, CACHE_DIR / f"AF-{uniprot}.pdb")
    exp_bytes = fetch(f"https://files.rcsb.org/download/{pdb_id}.pdb", CACHE_DIR / f"{pdb_id}.pdb")
    af_seq, af_coords, af_plddt = extract_chain(af_bytes, "A")
    exp_seq, exp_coords, _ = extract_chain(exp_bytes, chain_id)
    aligner = PairwiseAligner()
    aligner.mode = "global"
    aligner.substitution_matrix = substitution_matrices.load("BLOSUM62")
    aligner.open_gap_score = -10; aligner.extend_gap_score = -0.5
    aligner.target_end_gap_score = 0.0; aligner.query_end_gap_score = 0.0
    aln = aligner.align(af_seq, exp_seq)[0]
    tgt_blocks, qry_blocks = aln.aligned
    af_idx, exp_idx = [], []
    for (t0, t1), (q0, q1) in zip(tgt_blocks, qry_blocks):
        for k in range(t1 - t0):
            ti, qi = t0 + k, q0 + k
            if af_seq[ti] == exp_seq[qi]:
                af_idx.append(ti); exp_idx.append(qi)
    af_m, exp_m, plddt_m = af_coords[af_idx], exp_coords[exp_idx], af_plddt[af_idx]
    dist = kabsch_error(af_m, exp_m)
    return plddt_m / 100.0, (dist > 3.0).astype(np.float64), len(af_idx), af_url, pdb_id, chain_id

