    lam_synth = thresholds(sc, se_, 1000, alphas)   # "N=1000 synthetic proteins" knob used in the level formula
    lam_pool = thresholds(pc, pe, n + 1000, alphas)
    print(f"\n== regime: {regime} (synthetic pool: "
          f"{'same real mixed easy+hard distribution as the test pool' if regime=='informative_real' else 'REAL easy-only proteins (over-optimistic vs the real mixed test pool, which also contains hard real proteins)'}) ==")
