def thresholds(c, e, n_examples, target_levels):
    Tn, R = c.shape
    order = np.argsort(-c, axis=1)
    c_sorted = np.take_along_axis(c, order, axis=1)
    e_sorted = np.take_along_axis(e, order, axis=1)
    Sk = np.cumsum(e_sorted, axis=1)
    out = {}
    for a in target_levels:
        t = a - (1.0 - a) / n_examples
        cap = t * R
        k = (Sk <= cap).sum(axis=1)
        lam = np.empty(Tn)
        abstain_all = k <= 0; accept_all = k >= R; mid = ~abstain_all & ~accept_all
        lam[abstain_all] = np.inf; lam[accept_all] = -np.inf
        idx = k[mid]
        lam[mid] = 0.5 * (c_sorted[mid, idx - 1] + c_sorted[mid, idx])
        out[round(a, 3)] = lam
    return out

def bootstrap_draw(pool_c, pool_e, rng, shape):
    idx = rng.integers(0, len(pool_c), size=shape)
    return pool_c[idx], pool_e[idx]

# fixed bootstrap test pool, drawn once from the REAL (mixed easy+hard) empirical distribution
test_idx = rng.integers(0, len(full_c), size=Rtest)
tc, te = full_c[test_idx], full_e[test_idx]
tc_sorted_order = np.argsort(tc); tc_sorted = tc[tc_sorted_order]; te_by_c = te[tc_sorted_order]
suffix_err = np.concatenate([np.cumsum(te_by_c[::-1])[::-1], [0.0]])

def eval_thr(lam):
    lam = np.asarray(lam, float)
    pos = np.searchsorted(tc_sorted, lam, side="left")
    risk = suffix_err[pos] / Rtest
    abstain = pos / Rtest
    risk = np.where(np.isposinf(lam), 0.0, risk); abstain = np.where(np.isposinf(lam), 1.0, abstain)
    risk = np.where(np.isneginf(lam), te.mean(), risk); abstain = np.where(np.isneginf(lam), 0.0, abstain)
    return risk, abstain

def mc(x): return float(x.mean()), float(x.std() / np.sqrt(len(x)))

